const assert=require('node:assert/strict');
const state=require('../build/src/library-state.js');
const original=state.migrate('', ['template:cafe-bakery','template:cafe-bakery','unknown:bad']);
assert.deepEqual(original.projects[0].items,['template:cafe-bakery']);
assert.equal(state.migrate('{broken',original.projects[0].items).projects[0].items.length,1);
const imported={version:1,active:'default',projects:[{id:'default',name:'Imported café',items:['effect:scroll-reveal'],notes:'Bring the real logo'}]};
const merged=state.merge(original,imported,'test');
assert.equal(merged.projects.length,2);assert.equal(merged.active,'default');
assert.equal(merged.projects[0].items[0],'template:cafe-bakery');
assert.notEqual(merged.projects[1].id,merged.projects[0].id);
assert.equal(original.projects.length,1);
assert.equal(state.merge(merged,imported,'repeat').projects.length,2);
assert.throws(()=>state.validate({...imported,projects:[{...imported.projects[0],items:['javascript:alert'] }]}));
assert.throws(()=>state.validate({...imported,active:'missing'}));
assert.throws(()=>state.validate({...imported,projects:[{...imported.projects[0],notes:'x'.repeat(4001)}]}));
assert.equal(state.canCompare(390,'desktop'),false);
assert.equal(state.canCompare(1440,'mobile'),false);
assert.equal(state.canCompare(1440,'desktop'),true);
console.log('Library state checks passed: migration, deduplication, non-destructive restore, validation, responsive comparison.');
